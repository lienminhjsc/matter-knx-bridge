export type Lang = "vi" | "en";
const DICTS: Record<Lang, Dict> = { vi, en };
const KEY = "mb.lang";

function initialLang(): Lang {
    try {
        const v = localStorage.getItem(KEY);
        if (v === "vi" || v === "en") return v;
    } catch {
        // storage blocked by the browser: use the default
    }
    return "vi"; // Vietnamese by default; EN when the engineer picks it (remembered in the browser)
}

interface LangCtx {
    lang: Lang;
    t: Dict;
    setLang: (l: Lang) => void;
}

const Ctx = createContext<LangCtx>({ lang: "vi", t: vi, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
    const [lang, set] = useState<Lang>(initialLang);
    const setLang = (l: Lang) => {
        set(l);
        document.documentElement.lang = l;
        try {
            localStorage.setItem(KEY, l);
        } catch {
            // ignore
        }
    };
    return <Ctx.Provider value={{ lang, t: DICTS[lang], setLang }}>{children}</Ctx.Provider>;
}

export function useLang(): LangCtx {
    return useContext(Ctx);
}

export function LangSwitch() {
    const { lang, setLang, t } = useLang();
    return (
        <div className="lang" role="group" aria-label={t.language}>
            <button type="button" aria-pressed={lang === "vi"} onClick={() => setLang("vi")}>VI</button>
            <button type="button" aria-pressed={lang === "en"} onClick={() => setLang("en")}>EN</button>
        </div>
    );
}

export function locale(lang: Lang): string {
    return lang === "vi" ? "vi-VN" : "en-GB";
}
